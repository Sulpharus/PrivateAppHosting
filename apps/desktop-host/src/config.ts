import { publicOrigin } from '@mininode/manifest';
import { z } from 'zod';

const bool = z
  .string()
  .optional()
  .transform((value) => value === 'true' || value === '1');

const schema = z.object({
  /** The platform domain: the portal is here, apps are <slug>.<domain>, the API is api.<domain>. */
  MININODE_DOMAIN: z
    .string()
    .toLowerCase()
    .regex(/^[a-z0-9]([a-z0-9.-]*[a-z0-9])?$/, 'a host name such as mininode.localhost'),
  /** http on this computer, https behind a tunnel or reverse proxy. */
  MININODE_SCHEME: z.enum(['http', 'https']).default('http'),
  /** The port people type in the browser; omitted from addresses when it is the scheme's default. */
  MININODE_PORT: z.coerce.number().int().min(1).max(65535).default(8787),
  /** What the host listens on inside its container. */
  LISTEN_HOST: z.string().default('0.0.0.0'),
  LISTEN_PORT: z.coerce.number().int().min(1).max(65535).default(8787),

  /** The Supabase gateway (Kong) as the host reaches it. */
  GATEWAY_URL: z.url().default('http://kong:8000'),
  SUPABASE_PUBLISHABLE_KEY: z.string().min(1),
  SUPABASE_SECRET_KEY: z.string().min(1),

  /** Random secrets generated by the installer. */
  VAULT_KEY: z.string().min(1),
  GUACAMOLE_JSON_SECRET: z.string().min(1),
  NUCBOX_CONTROL_TOKEN: z.string().min(1),
  GOOGLE_CLIENT_ID: z.string().optional(),
  GOOGLE_CLIENT_SECRET: z.string().optional(),
  GOOGLE_TOKEN_KEY: z.string().optional(),
  VAPID_PUBLIC_KEY: z.string().optional(),
  VAPID_PRIVATE_KEY: z.string().optional(),
  ANTHROPIC_API_KEY: z.string().optional(),
  GEMINI_API_KEY: z.string().optional(),
  GITHUB_REPO: z.string().default(''),

  /** apps/<slug>/{assets,app.json} live below this folder. */
  DATA_DIR: z.string().default('/data'),
  /** Built portal (apps/portal/dist) and bundled workers. */
  PORTAL_DIST: z.string().default('/app/apps/portal/dist'),
  WORKERS_DIR: z.string().default('/app/dist-workers'),
  /** Set for tests and the first check: do not start the minute timer. */
  NO_SCHEDULER: bool,
});

export type DesktopConfig = z.infer<typeof schema> & {
  /** `http://mininode.localhost:8787`, with the port only when it is not the default. */
  portalUrl: string;
  apiUrl: string;
  aiUrl: string;
  /** What browsers and the workers call for Supabase (the host proxies it to the gateway). */
  supabaseUrl: string;
};

export function origin(config: z.infer<typeof schema>, subdomain?: string): string {
  return publicOrigin(
    { domain: config.MININODE_DOMAIN, scheme: config.MININODE_SCHEME, port: config.MININODE_PORT },
    subdomain,
  );
}

export function loadConfig(env: NodeJS.ProcessEnv = process.env): DesktopConfig {
  const parsed = schema.safeParse(env);
  if (!parsed.success) {
    const problems = parsed.error.issues.map(
      (issue) => `${issue.path.join('.')}: ${issue.message}`,
    );
    throw new Error(`invalid configuration:\n  ${problems.join('\n  ')}`);
  }
  const config = parsed.data;
  return {
    ...config,
    portalUrl: origin(config),
    apiUrl: origin(config, 'api'),
    aiUrl: origin(config, 'ai'),
    supabaseUrl: origin(config, 'supabase'),
  };
}
